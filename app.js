function todayKey(){
  const d = new Date().getDay();
  return WEEK_KEYS[d];
}

function setDate(){
  const d = new Date();
  const fmt = new Intl.DateTimeFormat('fa-IR',{
    weekday:'long', day:'numeric', month:'long'
  }).format(d);
  $('date').textContent = fmt;
  $('todayName').textContent = WEEK_DAYS[d.getDay()];
}

